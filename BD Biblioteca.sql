drop database if exists Biblioteca;
create database Biblioteca;
use Biblioteca;


-- 1. TABLAS INDEPENDIENTES / BASE

CREATE TABLE Usuarios (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    Nombre_Completo VARCHAR(150) NOT NULL,
    Contraseña VARCHAR(150) NOT NULL,
    DNI VARCHAR(20) NOT NULL UNIQUE,
    Email VARCHAR(150) NOT NULL UNIQUE,
    esProfesor BOOLEAN NOT NULL DEFAULT FALSE,
    esBibliotecario BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE Cursos (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    Turno VARCHAR(50) NOT NULL,
    Anio INT(1) NOT NULL,
    Division INT(1) NOT NULL
);

CREATE TABLE Carros (
    Numero INT PRIMARY KEY
);

CREATE TABLE Libros (
    ISBN VARCHAR(20) PRIMARY KEY,
    Titulo VARCHAR(255) NOT NULL,
    Anio_Lanzamiento INT
);

CREATE TABLE Autores (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    Nombre VARCHAR(150) NOT NULL
);

CREATE TABLE Generos (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    Nombre VARCHAR(100) NOT NULL
);

CREATE TABLE Elementos (
    Codigo VARCHAR(50) PRIMARY KEY,
    Tipo VARCHAR(100) NOT NULL
);


-- 2. TABLAS CON DEPENDENCIAS DIRECTAS / SECUNDARIAS

CREATE TABLE Computadoras (
    Numero INT PRIMARY KEY,
    Numero_Carro INT NOT NULL,
    Estado VARCHAR(50) NOT NULL,
    FOREIGN KEY (Numero_Carro) REFERENCES Carros(Numero) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE Ejemplares (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    ISBN_Libro VARCHAR(20) NOT NULL,
    FOREIGN KEY (ISBN_Libro) REFERENCES Libros(ISBN) ON DELETE CASCADE ON UPDATE CASCADE
);


-- 3. TABLAS DE RELACIÓN MUCHOS A MUCHOS (INTERMEDIAS)

CREATE TABLE Autores_Libros (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    ID_Autor INT NOT NULL,
    ISBN_Libro VARCHAR(20) NOT NULL,
    FOREIGN KEY (ID_Autor) REFERENCES Autores(ID) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (ISBN_Libro) REFERENCES Libros(ISBN) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE Generos_Libros (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    ISBN_Libro VARCHAR(20) NOT NULL,
    ID_Genero INT NOT NULL,
    FOREIGN KEY (ISBN_Libro) REFERENCES Libros(ISBN) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (ID_Genero) REFERENCES Generos(ID) ON DELETE CASCADE ON UPDATE CASCADE
);


-- 4. INFORMES

CREATE TABLE Informes_Computadoras (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    Descripcion TEXT NOT NULL,
    Numero_Computadora INT NOT NULL,
    ID_Bibliotecario INT NOT NULL,
    Fecha DATE NOT NULL,
    FOREIGN KEY (Numero_Computadora) REFERENCES Computadoras(Numero) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (ID_Bibliotecario) REFERENCES Usuarios(ID) ON DELETE CASCADE ON UPDATE CASCADE
);


-- 5. TABLAS DE PRÉSTAMOS

CREATE TABLE Prestamos_Computadoras (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    Hora_Inicio TIME NOT NULL,
    Hora_Limite TIME NOT NULL,
    Hora_Devolucion TIME,
    Numero_Computadora INT NOT NULL,
    ID_Usuario INT NOT NULL,
    ID_Curso INT NULL,
    FOREIGN KEY (Numero_Computadora) REFERENCES Computadoras(Numero) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (ID_Usuario) REFERENCES Usuarios(ID) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (ID_Curso) REFERENCES Cursos(ID) ON DELETE SET NULL ON UPDATE CASCADE
);

CREATE TABLE Prestamos_Carros (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    Hora_Inicio TIME NOT NULL,
    Hora_Limite TIME NOT NULL,
    Hora_Devolucion TIME,
    ID_Profesor INT NOT NULL,
    Numero_Carro INT NOT NULL,
    ID_Curso INT NULL,
    FOREIGN KEY (ID_Profesor) REFERENCES Usuarios(ID) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (Numero_Carro) REFERENCES Carros(Numero) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (ID_Curso) REFERENCES Cursos(ID) ON DELETE SET NULL ON UPDATE CASCADE
);

CREATE TABLE Prestamos_Libros (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    Fecha_Inicio DATETIME NOT NULL,
    Fecha_Limite DATETIME NOT NULL,
    Fecha_Devolucion DATE,
    ID_Usuario INT NOT NULL,
    ID_Ejemplar INT NOT NULL,
    ID_Curso INT NULL,
    FOREIGN KEY (ID_Usuario) REFERENCES Usuarios(ID) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (ID_Ejemplar) REFERENCES Ejemplares(ID) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (ID_Curso) REFERENCES Cursos(ID) ON DELETE SET NULL ON UPDATE CASCADE
);

CREATE TABLE Prestamos_Elementos (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    Hora_Inicio TIME NOT NULL,
    Hora_Limite TIME NOT NULL,
    Fecha_Devolucion DATE,
    ID_Usuario INT NOT NULL,
    Codigo_Elementos VARCHAR(50) NOT NULL,
    ID_Curso INT NULL,
    FOREIGN KEY (ID_Usuario) REFERENCES Usuarios(ID) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (Codigo_Elementos) REFERENCES Elementos(Codigo) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (ID_Curso) REFERENCES Cursos(ID) ON DELETE SET NULL ON UPDATE CASCADE
);